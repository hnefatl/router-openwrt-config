import contextlib
import dataclasses
import pathlib
import string
import tempfile

from typing import Self

from config_secrets import Secrets
from exit_codes import MissingSecretsFileError


@contextlib.contextmanager
def temp_directory():
    with tempfile.TemporaryDirectory() as d:
        yield pathlib.Path(d)


@dataclasses.dataclass
class File:
    # SoT file, either a plain file or a template.
    sot_path: pathlib.Path
    # The contents of the SoT, expanded if the file is a template.
    sot_expanded_contents: str
    target_path: pathlib.Path
    target_contents: str | None

    @classmethod
    def load(
        cls, sot_path: pathlib.Path, target_path: pathlib.Path, secrets: Secrets
    ) -> Self:
        f = cls(
            sot_path=sot_path,
            sot_expanded_contents="",
            target_path=target_path,
            target_contents=None,
        )
        f.reload_contents(secrets)
        return f

    def write_target(self, contents: str):
        self.target_path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        self.target_path.write_text(contents)

    def reload_contents(self, secrets: Secrets):
        self.target_contents = None
        if self.target_path.exists():
            self.target_contents = self.target_path.read_text()
            # Autogenerated configs use tabs, manually edited configs use spaces.
            # Do as much as possible with spaces locally.
            self.target_contents = self.target_contents.replace("\t", "    ")

        self.sot_expanded_contents = self.sot_path.read_text()
        if self.sot_path.suffix == ".tmpl":
            try:
                tmpl = string.Template(self.sot_expanded_contents)
                self.sot_expanded_contents = tmpl.substitute(secrets)
            except KeyError as e:
                raise MissingSecretsFileError(
                    f"missing secret when processing {self.sot_path}"
                ) from e


# Sorted by `sot_path`.
Files = list[File]


def files_from_dir(
    sot_dir: pathlib.Path, target_dir: pathlib.Path, secrets: Secrets
) -> Files:
    files = []
    frontier = list(sot_dir.iterdir())
    for sot_path in frontier:
        if sot_path.is_dir():
            # Descend into directories
            frontier.extend(sot_path.iterdir())
            continue
        elif not sot_path.is_file():
            continue

        target_path = target_dir / sot_path.relative_to(sot_dir)
        if sot_path.suffix == ".tmpl":
            target_path = target_path.with_suffix("")

        files.append(File.load(sot_path, target_path, secrets))

    files.sort(key=lambda f: f.sot_path)
    return files
